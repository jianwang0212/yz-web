function setLanguage(lang) {
    const requestedLang = lang === 'en' ? 'en' : 'zh';
    const pageSupportsEnglish = window.ziPageSupportsEnglish !== false;
    const effectiveLang = requestedLang === 'en' && !pageSupportsEnglish ? 'zh' : requestedLang;
    currentLang = effectiveLang;
    lang = effectiveLang;
    if (pageSupportsEnglish) {
        localStorage.setItem('language', requestedLang);
    }
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

    const body = document.body;
    const titleKey = body && body.getAttribute('data-i18n-title');
    if (titleKey && translations[lang] && translations[lang][titleKey]) {
        document.title = translations[lang][titleKey];
        document.querySelectorAll('meta[property="og:title"], meta[name="twitter:title"]').forEach(meta => {
            meta.setAttribute('content', translations[lang][titleKey]);
        });
    }

    const descriptionKey = body && body.getAttribute('data-i18n-description');
    if (descriptionKey && translations[lang] && translations[lang][descriptionKey]) {
        document.querySelectorAll('meta[name="description"], meta[property="og:description"], meta[name="twitter:description"]').forEach(meta => {
            meta.setAttribute('content', translations[lang][descriptionKey]);
        });
    }
    
    // Update html lang attribute
    const htmlElement = document.getElementById('html-lang');
    if (htmlElement) {
        htmlElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    }
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[lang][key];
            } else {
                // Check if translation contains HTML tags
                const translation = translations[lang][key];
                if (translation && translation.includes && translation.includes('<') && translation.includes('>')) {
                    element.innerHTML = translation;
                } else {
                    element.textContent = translation || '';
                }
            }
        }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
        const key = element.getAttribute('data-i18n-aria-label');
        if (translations[lang] && translations[lang][key]) {
            element.setAttribute('aria-label', translations[lang][key]);
        }
    });
    
    // Show/hide hero value text based on language
    const valueZh = document.querySelector('.value-zh');
    const valueEn = document.querySelector('.value-en');
    if (valueZh && valueEn) {
        if (lang === 'zh') {
            valueZh.style.display = 'block';
            valueEn.style.display = 'none';
        } else {
            valueZh.style.display = 'none';
            valueEn.style.display = 'block';
        }
    }
    
    // Update active language button (desktop and mobile)
    document.querySelectorAll('.lang-btn, .lang-btn-mobile').forEach(btn => {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
    });
    const activeLangBtn = document.getElementById(`lang-${lang}`);
    const activeLangBtnMobile = document.getElementById(`lang-${lang}-mobile`);
    if (activeLangBtn) {
        activeLangBtn.classList.add('active');
        activeLangBtn.setAttribute('aria-pressed', 'true');
    }
    if (activeLangBtnMobile) {
        activeLangBtnMobile.classList.add('active');
        activeLangBtnMobile.setAttribute('aria-pressed', 'true');
    }
    
    // Re-render monthly timeline if function exists
    if (typeof renderMonthlyTimeline === 'function') {
        renderMonthlyTimeline();
    }
}

// Keep a stable reference for pages whose own tools also define setLanguage().
window.setSiteLanguage = setLanguage;

function bindDelegatedLanguageToggle() {
    if (window.__ziLanguageDelegationBound) {
        return;
    }

    window.__ziLanguageDelegationBound = true;
    document.addEventListener('click', (event) => {
        const button = event.target.closest('#lang-zh, #lang-en, #lang-zh-mobile, #lang-en-mobile, .lang-btn, .lang-btn-mobile');
        if (!button) {
            return;
        }

        const text = button.textContent.trim().toLowerCase();
        const lang = button.id.includes('en') || text === 'english' ? 'en' : 'zh';
        event.preventDefault();
        event.stopPropagation();
        window.setSiteLanguage(lang);
    });
}

// Initialize language - try multiple strategies
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        bindDelegatedLanguageToggle();
        window.setSiteLanguage(currentLang);
    });
} else {
    // DOM is already loaded
    bindDelegatedLanguageToggle();
    window.setSiteLanguage(currentLang);
}
