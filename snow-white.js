function getSnowLanguage() {
    return localStorage.getItem('language') === 'en' ? 'en' : 'zh';
}

function snowText(key) {
    const lang = getSnowLanguage();
    const messages = {
        zh: {
            downloading: '下载中',
            incorrect: '密码不正确',
            failed: '下载失败，请稍后再试',
            network: '网络错误，请稍后再试',
            submit: '下载'
        },
        en: {
            downloading: 'Downloading',
            incorrect: 'Incorrect access code',
            failed: 'Download failed. Please try again later.',
            network: 'Network error. Please try again later.',
            submit: 'Download'
        }
    };
    return messages[lang][key];
}

function applySnowLanguage() {
    const lang = getSnowLanguage();
    const translations = snowCopy[lang];

    Object.entries(translations).forEach(([selector, value]) => {
        document.querySelectorAll(selector).forEach((element) => {
            if (value.includes('<')) {
                element.innerHTML = value;
            } else {
                element.textContent = value;
            }
        });
    });

    document.querySelectorAll('[data-protected-file]').forEach((button) => {
        const key = button.dataset.protectedFile;
        if (snowDownloadLabels[lang][key]) {
            button.dataset.downloadLabel = snowDownloadLabels[lang][key];
        }
    });
}

function initSnowLanguage() {
    applySnowLanguage();
    window.addEventListener('site-language-change', applySnowLanguage);
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initSnowLanguage);
} else {
    initSnowLanguage();
}

const audio = document.getElementById('snow-audio-player');
const canvas = document.getElementById('snow-visualizer');

if (audio && canvas) {
    const ctx = canvas.getContext('2d');
    const AudioContextCtor = window.AudioContext || window.webkitAudioContext;
    let audioContext;
    let analyser;
    let source;
    let dataArray;
    let animationFrame;
    let seeded = 0;

    const palette = ['#b7372b', '#1e6f61', '#c08a2d', '#171311'];

    function resizeCanvas() {
        const ratio = window.devicePixelRatio || 1;
        const rect = canvas.getBoundingClientRect();
        canvas.width = Math.max(1, Math.floor(rect.width * ratio));
        canvas.height = Math.max(1, Math.floor(rect.height * ratio));
    }

    function drawIdle() {
        const width = canvas.width;
        const height = canvas.height;
        ctx.clearRect(0, 0, width, height);
        for (let i = 0; i < 72; i += 1) {
            const x = (i / 71) * width;
            const base = Math.sin(i * 0.48 + seeded) * 0.28 + Math.sin(i * 0.13) * 0.2;
            const barHeight = (0.26 + Math.abs(base)) * height * 0.58;
            ctx.fillStyle = palette[i % palette.length];
            ctx.globalAlpha = 0.32;
            ctx.fillRect(x, (height - barHeight) / 2, Math.max(2, width / 120), barHeight);
        }
        seeded += 0.01;
        ctx.globalAlpha = 1;
    }

    function drawActive() {
        if (!analyser || !dataArray) return;
        analyser.getByteFrequencyData(dataArray);
        const width = canvas.width;
        const height = canvas.height;
        const bars = 88;
        const step = Math.floor(dataArray.length / bars);
        const barWidth = width / bars;

        ctx.clearRect(0, 0, width, height);
        for (let i = 0; i < bars; i += 1) {
            const value = dataArray[i * step] / 255;
            const eased = Math.pow(value, 0.82);
            const barHeight = Math.max(3, eased * height * 0.82);
            ctx.fillStyle = palette[i % palette.length];
            ctx.globalAlpha = 0.34 + eased * 0.56;
            ctx.fillRect(i * barWidth, (height - barHeight) / 2, Math.max(2, barWidth - 3), barHeight);
        }
        ctx.globalAlpha = 1;
        animationFrame = requestAnimationFrame(drawActive);
    }

    function bootAudioGraph() {
        if (audioContext || !AudioContextCtor) return;
        audioContext = new AudioContextCtor();
        analyser = audioContext.createAnalyser();
        analyser.fftSize = 256;
        dataArray = new Uint8Array(analyser.frequencyBinCount);
        source = audioContext.createMediaElementSource(audio);
        source.connect(analyser);
        analyser.connect(audioContext.destination);
    }

    function renderIdleLoop() {
        if (!audio.paused) return;
        drawIdle();
        animationFrame = requestAnimationFrame(renderIdleLoop);
    }

    resizeCanvas();
    renderIdleLoop();

    audio.addEventListener('play', async () => {
        bootAudioGraph();
        if (!audioContext) {
            return;
        }
        if (audioContext.state === 'suspended') {
            await audioContext.resume();
        }
        cancelAnimationFrame(animationFrame);
        drawActive();
    });

    audio.addEventListener('pause', () => {
        cancelAnimationFrame(animationFrame);
        renderIdleLoop();
    });

    audio.addEventListener('ended', () => {
        cancelAnimationFrame(animationFrame);
        renderIdleLoop();
    });

    window.addEventListener('resize', () => {
        resizeCanvas();
        if (audio.paused) drawIdle();
    });
}

const protectedDownloadButtons = document.querySelectorAll('[data-protected-file]');
const downloadModal = document.getElementById('snow-download-modal');
const downloadForm = document.getElementById('snow-download-form');
const downloadPassword = document.getElementById('snow-download-password');
const downloadTarget = document.getElementById('snow-download-target');
const downloadStatus = document.getElementById('snow-download-status');
const closeDownloadButtons = document.querySelectorAll('[data-snow-download-close]');

if (protectedDownloadButtons.length && downloadModal && downloadForm && downloadPassword) {
    let pendingFile = '';
    let lastTrigger = null;

    const downloadNames = {
        'full-score': 'snow-white-full-score.pdf',
        'lead-sheet': 'snow-white-lead-sheet.pdf',
        'vocal-score': 'snow-white-vocal-score.pdf',
        charts: 'snow-white-charts.pdf',
        'piano-arrangement': 'snow-white-piano-arrangement.pdf'
    };

    function openDownloadModal(button) {
        pendingFile = button.dataset.protectedFile || '';
        lastTrigger = button;
        if (downloadTarget) {
            downloadTarget.textContent = button.dataset.downloadLabel || 'Protected score file';
        }
        if (downloadStatus) {
            downloadStatus.textContent = '';
        }
        downloadPassword.value = '';
        downloadModal.hidden = false;
        downloadPassword.focus();
    }

    function closeDownloadModal() {
        downloadModal.hidden = true;
        pendingFile = '';
        downloadForm.reset();
        if (downloadStatus) {
            downloadStatus.textContent = '';
        }
        if (lastTrigger) {
            lastTrigger.focus();
        }
    }

    function saveBlob(blob, fileName) {
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = fileName;
        document.body.appendChild(link);
        link.click();
        link.remove();
        URL.revokeObjectURL(url);
    }

    protectedDownloadButtons.forEach((button) => {
        button.addEventListener('click', () => openDownloadModal(button));
    });

    closeDownloadButtons.forEach((button) => {
        button.addEventListener('click', closeDownloadModal);
    });

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape' && !downloadModal.hidden) {
            closeDownloadModal();
        }
    });

    downloadForm.addEventListener('submit', async (event) => {
        event.preventDefault();
        if (!pendingFile) return;

        const submitButton = downloadForm.querySelector('button[type="submit"]');
        if (submitButton) {
            submitButton.disabled = true;
            submitButton.textContent = snowText('downloading');
        }
        if (downloadStatus) {
            downloadStatus.textContent = '';
        }

        try {
            const response = await fetch('/api/snow-white/download', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify({
                    file: pendingFile,
                    password: downloadPassword.value
                })
            });

            if (!response.ok) {
                if (downloadStatus) {
                    downloadStatus.textContent = response.status === 401
                        ? snowText('incorrect')
                        : snowText('failed');
                }
                return;
            }

            const blob = await response.blob();
            saveBlob(blob, downloadNames[pendingFile] || 'snow-white-score.pdf');
            closeDownloadModal();
        } catch (_error) {
            if (downloadStatus) {
                downloadStatus.textContent = snowText('network');
            }
        } finally {
            if (submitButton) {
                submitButton.disabled = false;
                submitButton.textContent = snowText('submit');
            }
        }
    });
}
